import { createHash, randomUUID, timingSafeEqual } from "node:crypto";
import { NextResponse } from "next/server";
import { getDb } from "@/db";
import { images } from "@/db/schema";
import { getAvalClient, AVAL_IMAGE_MODEL } from "@/server/aval/client";
import { getOrCreateSession } from "@/server/credits";
import { getStorage } from "@/server/storage";
import { buildImagePrompt } from "@/lib/image-prompt";

/**
 * Library seed API (ticket 15): creates PUBLIC seed rows (is_seed=true) by
 * calling the Aval image API directly, server-side. Does NOT consume credits
 * — seeding is an operator action, protected by the `x-seed-key` header
 * compared against SEED_SECRET (.env.local, generated by the operator).
 *
 * POST { category, title, description, seedPrompt, material?, aspectRatio? }
 * → { imageId, url }
 * The motif in `seedPrompt` is wrapped with the standard studio constraint
 * block (src/lib/image-prompt.ts) exactly like the user-facing flow.
 */

/** 7-category taxonomy — hand-synced twin of the list in /api/library. */
const CATEGORIES: ReadonlyArray<{ slug: string }> = [
  { slug: "confectionery" },
  { slug: "resin" },
  { slug: "candle" },
  { slug: "soap" },
  { slug: "plaster" },
  { slug: "figures" },
  { slug: "keepsake" },
];

const ASPECT_RATIOS = [
  "1:1",
  "3:4",
  "4:3",
  "9:16",
  "16:9",
  "2:3",
  "3:2",
  "5:4",
  "4:5",
  "21:9",
] as const;

/** Aval Gemini-image response shape (issue 01). */
interface AvalImageResponse {
  choices?: Array<{
    message?: {
      images?: Array<{ image_url?: { url?: string } }>;
    };
  }>;
}

function extForMime(mime: string): string {
  if (mime === "image/jpeg") return ".jpg";
  if (mime === "image/webp") return ".webp";
  return ".png";
}

/** Constant-time compare of the seed key against SEED_SECRET. */
function isAuthorized(req: Request): boolean {
  const secret = process.env.SEED_SECRET;
  const provided = req.headers.get("x-seed-key") ?? "";
  if (!secret || !provided) return false;
  const a = createHash("sha256").update(secret).digest();
  const b = createHash("sha256").update(provided).digest();
  return timingSafeEqual(a, b);
}

export async function POST(req: Request) {
  if (!isAuthorized(req)) {
    return NextResponse.json({ error: "unauthorized" }, { status: 401 });
  }

  let body: {
    category?: unknown;
    title?: unknown;
    description?: unknown;
    seedPrompt?: unknown;
    material?: unknown;
    aspectRatio?: unknown;
  };
  try {
    body = await req.json();
  } catch {
    return NextResponse.json({ error: "invalid_json" }, { status: 400 });
  }

  const category =
    typeof body.category === "string" &&
    CATEGORIES.some((c) => c.slug === body.category)
      ? body.category
      : null;
  const title =
    typeof body.title === "string" ? body.title.trim().slice(0, 120) : "";
  const description =
    typeof body.description === "string"
      ? body.description.trim().slice(0, 400)
      : "";
  const seedPrompt =
    typeof body.seedPrompt === "string"
      ? body.seedPrompt.trim().slice(0, 800)
      : "";
  const material =
    typeof body.material === "string" && body.material.trim()
      ? body.material.trim().slice(0, 200)
      : undefined;

  if (!category || !title || !description || !seedPrompt) {
    return NextResponse.json(
      { error: "invalid_body", message: "دسته/عنوان/توضیح/پرامپت الزامی است." },
      { status: 400 },
    );
  }
  const aspectRatio = (
    ASPECT_RATIOS as readonly string[]
  ).includes(typeof body.aspectRatio === "string" ? body.aspectRatio : "")
    ? (body.aspectRatio as (typeof ASPECT_RATIOS)[number])
    : "1:1";

  const sessionId = await getOrCreateSession();
  const db = getDb();
  const storage = getStorage();
  const imageId = randomUUID();

  // Full studio prompt: motif + constraint block (issue 07 copy).
  const prompt = buildImagePrompt(seedPrompt, material ? { material } : undefined);

  try {
    const client = getAvalClient();
    // Same call shape as /api/image (issue 01): chat-completions with
    // modalities + generationConfig extras.
    const completion = (await client.chat.completions.create({
      model: AVAL_IMAGE_MODEL,
      modalities: ["image", "text"],
      messages: [{ role: "user", content: prompt }],
      generationConfig: {
        imageConfig: { aspectRatio, imageSize: "1K" },
      },
    } as Parameters<typeof client.chat.completions.create>[0])) as unknown as Awaited<
      ReturnType<typeof client.chat.completions.create>
    > &
      AvalImageResponse;

    const dataUrl =
      completion.choices?.[0]?.message?.images?.[0]?.image_url?.url;
    if (!dataUrl || !dataUrl.startsWith("data:")) {
      throw new Error("Aval returned no image payload");
    }
    const [header, b64] = dataUrl.split(",", 2);
    const mime = /^data:([^;]+)/.exec(header ?? "")?.[1] ?? "image/png";
    const bytes = Buffer.from(b64 ?? "", "base64");
    if (bytes.length === 0) throw new Error("Aval image payload was empty");

    const key = `images/${sessionId}/${imageId}${extForMime(mime)}`;
    await storage.put(key, new Uint8Array(bytes), mime);

    await db.insert(images).values({
      id: imageId,
      sessionId,
      kind: "generated",
      storageKey: key,
      mime,
      isSeed: true,
      meta: {
        title,
        category,
        description,
        seedPrompt,
        prompt,
        aspectRatio,
        model: AVAL_IMAGE_MODEL,
        seed: true,
      },
    });

    return NextResponse.json({ imageId, url: storage.publicUrl(key) });
  } catch (err) {
    console.error("[api/library/seed] generation failed", err);
    return NextResponse.json({ error: "generation_failed" }, { status: 502 });
  }
}
